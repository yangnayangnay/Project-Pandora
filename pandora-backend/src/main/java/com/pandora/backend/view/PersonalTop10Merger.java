package com.pandora.backend.view;

import org.springframework.stereotype.Component;

import java.util.*;

@Component
public class PersonalTop10Merger {

    public List<Map<String, Object>> merge(List<Map<String, Object>> injected, List<Map<String, Object>> autoGenerated) {
        List<Map<String, Object>> result = new ArrayList<>();

        injected.sort(Comparator.comparingInt(this::getRank));
        result.addAll(injected);

        Set<String> injectedContents = new HashSet<>();
        for (Map<String, Object> item : injected) {
            String content = getStr(item, "CONTENT", "content");
            if (!content.isEmpty()) {
                injectedContents.add(content);
            }
        }

        for (Map<String, Object> auto : autoGenerated) {
            String content = getStr(auto, "content", "CONTENT");
            if (!injectedContents.contains(content)) {
                result.add(auto);
            }
            if (result.size() >= 10) {
                break;
            }
        }

        if (result.size() > 10) {
            result = result.subList(0, 10);
        }

        return result;
    }

    private int getRank(Map<String, Object> map) {
        Object rank = map.get("rank_order");
        if (rank == null) rank = map.get("RANK_ORDER");
        if (rank == null) return 99;
        return ((Number) rank).intValue();
    }

    private String getStr(Map<String, Object> map, String key1, String key2) {
        Object val = map.get(key1);
        if (val == null) val = map.get(key2);
        return val != null ? val.toString() : "";
    }
}