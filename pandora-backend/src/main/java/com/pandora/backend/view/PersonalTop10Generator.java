package com.pandora.backend.view;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.stereotype.Service;

import java.util.*;

@Service
public class PersonalTop10Generator {

    private static final Logger log = LoggerFactory.getLogger(PersonalTop10Generator.class);

    // 角色英文 → 中文映射（未知值兜底返回原值）
    private static final Map<String, String> ROLE_CN_MAP = Map.of(
            "FOUNDER", "创始人",
            "ADMIN", "管理员",
            "DEPT_HEAD", "部门主管",
            "TEAM_LEADER", "团队负责人",
            "EMPLOYEE", "员工"
    );

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Autowired
    private LogAggregationStrategy logAggregationStrategy;

    @Autowired
    private PersonalTop10Merger personalTop10Merger;

    @Value("${pandora.personal.log-range-days:30}")
    private int logRangeDays;

    public List<Map<String, Object>> generate(Long userId) {
        List<Map<String, Object>> injected = getInjectedItems(userId);
        List<Map<String, Object>> autoGenerated = getAutoGeneratedItems(userId);
        return personalTop10Merger.merge(injected, autoGenerated);
    }

    private List<Map<String, Object>> getInjectedItems(Long userId) {
        List<Map<String, Object>> manualItems = jdbcTemplate.queryForList(
                "SELECT * FROM top10_works WHERE user_id = ? AND work_type = 'PERSONAL_IMPORTANT' AND deleted = 0 ORDER BY rank_order LIMIT 10", userId);
        List<Map<String, Object>> result = new ArrayList<>();
        for (Map<String, Object> item : manualItems) {
            Map<String, Object> manual = new HashMap<>(item);
            manual.put("is_auto_filled", false);
            result.add(manual);
        }
        return result;
    }

    private List<Map<String, Object>> getAutoGeneratedItems(Long userId) {
        List<Map<String, Object>> result = new ArrayList<>();

        // 账号信息自动条目（排在所有自动条目最前）
        try {
            result.addAll(getAccountInfoItems(userId));
        } catch (Exception e) {
            log.warn("账号信息条目生成失败: userId={}, error={}", userId, e.getMessage());
        }

        try {
            Map<String, Object> user = jdbcTemplate.queryForMap(
                    "SELECT birthday FROM users WHERE id = ? AND deleted = 0", userId);
            Object birthdayObj = user.get("birthday");
            if (birthdayObj != null) {
                String birthdayStr = birthdayObj.toString();
                java.sql.Date today = new java.sql.Date(System.currentTimeMillis());
                String todayStr = today.toString();
                String birthdayMd = birthdayStr.length() >= 10 ? birthdayStr.substring(5) : "";
                String todayMd = todayStr.length() >= 10 ? todayStr.substring(5) : "";
                if (!birthdayMd.isEmpty() && birthdayMd.equals(todayMd)) {
                    Map<String, Object> wish = new HashMap<>();
                    wish.put("rank_order", result.isEmpty() ? 1 : result.size() + 1);
                    wish.put("content", "\u751F\u65E5\u5FEB\u4E50\uFF01");
                    wish.put("is_auto_filled", true);
                    wish.put("work_type", "BIRTHDAY_WISH");
                    wish.put("source_note", "生日祝福");
                    result.add(wish);
                }
            }
        } catch (Exception ignored) {}

        try {
            List<Map<String, Object>> logItems = logAggregationStrategy.aggregate(userId, logRangeDays);
            int startRank = result.isEmpty() ? 1 : result.size() + 1;
            for (int i = 0; i < logItems.size(); i++) {
                logItems.get(i).put("rank_order", startRank + i);
            }
            result.addAll(logItems);
        } catch (Exception e) {
            log.warn("日志聚合失败，回退空列表: userId={}, error={}", userId, e.getMessage());
        }

        return result;
    }

    /**
     * 根据用户账号基础信息及关联表数据，生成账号信息自动条目。
     * 条目顺序：真实姓名 → 用户名 → 部门 → 团队 → 角色 → 职位 → MBTI → 手机号 → 邮箱
     * 空值字段跳过；基础查询失败返回空列表；MBTI/职位子查询失败仅跳过对应条目。
     */
    private List<Map<String, Object>> getAccountInfoItems(Long userId) {
        List<Map<String, Object>> result = new ArrayList<>();
        int rank = 1;

        // 账号基础信息联合查询（显式列名选取，排除 password_hash / id_card 等敏感字段）
        Map<String, Object> user;
        try {
            user = jdbcTemplate.queryForMap(
                    "SELECT u.username, u.real_name, u.role, u.phone, u.email, " +
                            "d.name AS department_name, t.name AS team_name " +
                            "FROM users u " +
                            "LEFT JOIN departments d ON u.department_id = d.id AND d.deleted = 0 " +
                            "LEFT JOIN teams t ON u.team_id = t.id AND t.deleted = 0 " +
                            "WHERE u.id = ? AND u.deleted = 0", userId);
        } catch (Exception e) {
            log.warn("账号信息查询失败: userId={}, error={}", userId, e.getMessage());
            return Collections.emptyList();
        }

        // MBTI 最新记录查询（独立 try-catch，失败不影响其他条目）
        String mbtiType = null;
        try {
            Map<String, Object> mbti = jdbcTemplate.queryForMap(
                    "SELECT personality_type FROM mbti_reports " +
                            "WHERE user_id = ? AND deleted = 0 " +
                            "ORDER BY generated_at DESC LIMIT 1", userId);
            Object mbtiObj = mbti.get("personality_type");
            if (mbtiObj != null) {
                String tmp = mbtiObj.toString().trim();
                if (!tmp.isEmpty()) mbtiType = tmp;
            }
        } catch (Exception ignored) {}

        // 职位查询（独立 try-catch，失败不影响其他条目）
        String position = null;
        try {
            Map<String, Object> emp = jdbcTemplate.queryForMap(
                    "SELECT position FROM employee_records " +
                            "WHERE registered_user_id = ? AND deleted = 0 " +
                            "AND position IS NOT NULL LIMIT 1", userId);
            Object posObj = emp.get("position");
            if (posObj != null) {
                String tmp = posObj.toString().trim();
                if (!tmp.isEmpty()) position = tmp;
            }
        } catch (Exception ignored) {}

        // 按固定顺序逐字段构造条目（空值跳过）
        rank = addAccountItem(result, rank, user.get("real_name"), "账号信息-真实姓名");
        rank = addAccountItem(result, rank, user.get("username"), "账号信息-用户名");
        rank = addAccountItem(result, rank, user.get("department_name"), "账号信息-部门");
        rank = addAccountItem(result, rank, user.get("team_name"), "账号信息-团队");

        // 角色字段：英文转中文后作为 content
        Object roleObj = user.get("role");
        if (roleObj != null) {
            String roleCn = toChineseRole(roleObj.toString());
            rank = addAccountItem(result, rank, roleCn, "账号信息-角色");
        }

        rank = addAccountItem(result, rank, position, "账号信息-职位");
        rank = addAccountItem(result, rank, mbtiType, "账号信息-MBTI");
        rank = addAccountItem(result, rank, user.get("phone"), "账号信息-手机号");
        rank = addAccountItem(result, rank, user.get("email"), "账号信息-邮箱");

        return result;
    }

    /**
     * 角色英文转中文。null 返回 null；已知角色返回中文名；未知角色原样返回（兜底）。
     */
    private static String toChineseRole(String role) {
        if (role == null) return null;
        return ROLE_CN_MAP.getOrDefault(role, role);
    }

    /**
     * 构造单条账号信息条目并追加到结果列表。值为 null 或空白时跳过，返回原 rank；否则追加条目并返回 rank+1。
     */
    private int addAccountItem(List<Map<String, Object>> result, int rank, Object value, String note) {
        if (value == null) return rank;
        String str = value.toString().trim();
        if (str.isEmpty()) return rank;
        Map<String, Object> item = new HashMap<>();
        item.put("rank_order", rank);
        item.put("content", str);
        item.put("is_auto_filled", true);
        item.put("work_type", "ACCOUNT_INFO");
        item.put("source_note", note);
        result.add(item);
        return rank + 1;
    }
}