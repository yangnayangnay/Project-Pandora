package com.pandora.backend.view;

import com.pandora.backend.ai.AIGatewayService;
import com.pandora.backend.ai.AiTransmitConfig;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;

import java.util.*;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.TimeUnit;

@Service
public class PersonalTop10Generator {

    private static final Logger log = LoggerFactory.getLogger(PersonalTop10Generator.class);

    // Round23 REQ-23-01: AI 分析条目调用限时（秒），超时静默降级返回 null
    // Round25 L10 放宽 3→10 秒: GPU 热态推理 280 token 实测需 3~4 秒，原 3 秒限时处于成败边缘，
    // 加网络余量放宽到 10 秒（仍低于页面级超时）；超时静默降级语义与 1 小时内存缓存兜底机制不变
    private static final long AI_CALL_TIMEOUT_SECONDS = 10;

    // Round28 REQ-28-11: AI 分析文本缓存改为按日失效（废除 Round23 的 1 小时 TTL），
    // 每日首次查看重新生成、当日复用；个人信息变更由 invalidateUser 主动失效（REQ-28-12）
    private final Map<Long, CachedAnalysis> aiAnalysisCache = new ConcurrentHashMap<>();

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Autowired
    private PersonalTop10Merger personalTop10Merger;

    @Autowired
    private AIGatewayService aiGatewayService;

    public List<Map<String, Object>> generate(Long userId, AiTransmitConfig aiConfig) {
        List<Map<String, Object>> injected = getInjectedItems(userId);
        List<Map<String, Object>> autoGenerated = getAutoGeneratedItems(userId);
        // Round23 REQ-23-01: AI 分析条目（至多 1 条）追加到自动条目末位，随 Merger 统一去重与截断 10 条
        Map<String, Object> aiItem = getAiAnalysisItem(userId, aiConfig);
        if (aiItem != null) {
            aiItem.put("rank_order", autoGenerated.isEmpty() ? 1 : autoGenerated.size() + 1);
            autoGenerated.add(aiItem);
        }
        return personalTop10Merger.merge(injected, autoGenerated);
    }

    /**
     * Round28 REQ-28-12: 个人信息变更失效入口（资料/MBTI/部门/职位等全量数据源变更挂点调用）。
     * O(1) 线程安全移除该用户缓存条目；失效幂等、多次调用同效；纯内存操作不阻塞调用方——
     * 重生成严格发生在下次查看且当日无有效缓存时，防止生成风暴。
     */
    public void invalidateUser(Long userId) {
        if (userId == null) return;
        CachedAnalysis removed = aiAnalysisCache.remove(userId);
        if (removed != null) {
            log.info("个人十大AI点评缓存已失效: userId={}", userId);
        }
    }

    // 角色英文 → 中文映射（未知值兜底返回原值）
    private static final Map<String, String> ROLE_CN_MAP = Map.of(
            "FOUNDER", "创始人",
            "ADMIN", "管理员",
            "DEPT_HEAD", "部门主管",
            "TEAM_LEADER", "团队负责人",
            "EMPLOYEE", "员工"
    );

    private List<Map<String, Object>> getInjectedItems(Long userId) {
        // Round23 REQ-23-01: 仅个人信息类（category='PERSONAL_INFO'）手动条目进入个人十大信息象限，
        // 工作事项类（WORK_ITEM）手动条目不再展示
        List<Map<String, Object>> manualItems = jdbcTemplate.queryForList(
                "SELECT * FROM top10_works WHERE user_id = ? AND work_type = 'PERSONAL_IMPORTANT' AND deleted = 0 AND category = 'PERSONAL_INFO' ORDER BY rank_order LIMIT 10", userId);
        List<Map<String, Object>> result = new ArrayList<>();
        for (Map<String, Object> item : manualItems) {
            Map<String, Object> manual = new HashMap<>(item);
            manual.put("is_auto_filled", false);
            result.add(manual);
        }
        return result;
    }

    private List<Map<String, Object>> getAutoGeneratedItems(Long userId) {
        List<Map<String, Object>> result = new ArrayList<>();

        // 账号信息自动条目（排在所有自动条目最前）
        try {
            result.addAll(getAccountInfoItems(userId));
        } catch (Exception e) {
            log.warn("账号信息条目生成失败: userId={}, error={}", userId, e.getMessage());
        }

        try {
            Map<String, Object> user = jdbcTemplate.queryForMap(
                    "SELECT birthday FROM users WHERE id = ? AND deleted = 0", userId);
            Object birthdayObj = user.get("birthday");
            if (birthdayObj != null) {
                String birthdayStr = birthdayObj.toString();
                java.sql.Date today = new java.sql.Date(System.currentTimeMillis());
                String todayStr = today.toString();
                String birthdayMd = birthdayStr.length() >= 10 ? birthdayStr.substring(5) : "";
                String todayMd = todayStr.length() >= 10 ? todayStr.substring(5) : "";
                if (!birthdayMd.isEmpty() && birthdayMd.equals(todayMd)) {
                    Map<String, Object> wish = new HashMap<>();
                    wish.put("rank_order", result.isEmpty() ? 1 : result.size() + 1);
                    wish.put("content", "\u751F\u65E5\u5FEB\u4E50\uFF01");
                    wish.put("is_auto_filled", true);
                    wish.put("work_type", "BIRTHDAY_WISH");
                    wish.put("source_note", "生日祝福");
                    result.add(wish);
                }
            }
        } catch (Exception ignored) {}

        // Round23 REQ-23-01: 日志聚合条目（AUTO_FROM_LOG）已移除，个人十大信息不再包含任何日志工作事项

        return result;
    }

    /**
     * Round23 REQ-23-01: 生成 AI 分析条目（至多 1 条）。
     * 缓存命中且未过期 → 直接复用；否则组装用户摘要 + 积极基调提示词，
     * 经 CompletableFuture 10 秒限时调用 AI 网关，成功且非空写入内存缓存（TTL 1 小时）；
     * 超时/异常/空结果 → 返回 null 静默降级（不影响其余条目生成）。
     */
    private Map<String, Object> getAiAnalysisItem(Long userId, AiTransmitConfig aiConfig) {
        // Round28 REQ-28-11: 按日失效——缓存命中条件为 generatedDate 等于服务器当日日期
        // （时钟回拨边界取保守策略：日期不一致即失效重生成）
        CachedAnalysis cached = aiAnalysisCache.get(userId);
        if (cached != null && java.time.LocalDate.now().toString().equals(cached.generatedDate)) {
            log.info("AI分析条目缓存命中（当日）: userId={}", userId);
            return buildAiAnalysisItem(cached.text);
        }

        String prompt = buildAiPrompt(userId);
        if (prompt == null) {
            return null;
        }

        try {
            CompletableFuture<String> aiFuture = CompletableFuture.supplyAsync(() -> {
                Map<String, Object> aiResult = aiGatewayService.invoke(prompt, "PERSONAL_TOP10_AI", aiConfig);
                Object resultText = aiResult.get("result");
                return resultText != null ? resultText.toString() : null;
            });
            String text = aiFuture.get(AI_CALL_TIMEOUT_SECONDS, TimeUnit.SECONDS);
            if (text == null || text.trim().isEmpty()) {
                return null;
            }
            String trimmed = text.trim();
            aiAnalysisCache.put(userId, new CachedAnalysis(trimmed, java.time.LocalDate.now().toString()));
            log.info("AI分析条目生成成功并写入缓存（当日）: userId={}", userId);
            return buildAiAnalysisItem(trimmed);
        } catch (Exception e) {
            log.warn("AI分析条目生成失败，静默降级: userId={}, error={}", userId, e.getMessage());
            return null;
        }
    }

    /**
     * Round23 REQ-23-01: 组装用户摘要 + 积极基调提示词（60 字以内点评、鼓励基调、禁止消极表述）。
     * 摘要含真实姓名/角色/MBTI/任务完成率概要；基础用户查询失败时返回 null（跳过 AI 条目）。
     */
    private String buildAiPrompt(Long userId) {
        String realName = null;
        String role = null;
        try {
            Map<String, Object> user = jdbcTemplate.queryForMap(
                    "SELECT real_name, username, role FROM users WHERE id = ? AND deleted = 0", userId);
            realName = strOrNull(user.get("real_name"));
            if (realName == null) {
                realName = strOrNull(user.get("username"));
            }
            role = strOrNull(user.get("role"));
        } catch (Exception e) {
            log.warn("AI分析用户摘要查询失败: userId={}, error={}", userId, e.getMessage());
            return null;
        }

        String mbtiType = null;
        try {
            Map<String, Object> mbti = jdbcTemplate.queryForMap(
                    "SELECT personality_type FROM mbti_reports WHERE user_id = ? AND deleted = 0 ORDER BY generated_at DESC LIMIT 1", userId);
            mbtiType = strOrNull(mbti.get("personality_type"));
        } catch (Exception ignored) {}

        Integer totalTasks = null;
        Integer completedTasks = null;
        try {
            totalTasks = jdbcTemplate.queryForObject(
                    "SELECT COUNT(*) FROM tasks WHERE assignee_id = ? AND deleted = 0", Integer.class, userId);
            completedTasks = jdbcTemplate.queryForObject(
                    "SELECT COUNT(*) FROM tasks WHERE assignee_id = ? AND deleted = 0 AND status IN ('COMPLETED','CONFIRMED')", Integer.class, userId);
        } catch (Exception ignored) {}

        StringBuilder summary = new StringBuilder();
        if (realName != null) summary.append("真实姓名:").append(realName).append("; ");
        if (role != null) summary.append("角色:").append(toChineseRole(role)).append("; ");
        if (mbtiType != null) summary.append("MBTI:").append(mbtiType).append("; ");
        if (totalTasks != null) {
            summary.append("任务完成率:").append(completedTasks != null ? completedTasks : 0)
                    .append("/").append(totalTasks);
        }
        if (summary.length() == 0) {
            return null;
        }

        return "请根据以下用户信息生成一条 60 字以内、积极向上的个人优势点评，鼓励基调，禁止消极表述：" + summary;
    }

    /**
     * Round23 REQ-23-01: 构造 AI_ANALYSIS 条目，键结构对齐既有 AUTO_FROM_LOG 条目
     * （rank_order/content/is_auto_filled/work_type/source_note），App 端按 content 键读取展示。
     */
    private Map<String, Object> buildAiAnalysisItem(String text) {
        Map<String, Object> item = new HashMap<>();
        item.put("rank_order", 99);
        item.put("content", text);
        item.put("is_auto_filled", true);
        item.put("work_type", "AI_ANALYSIS");
        item.put("source_note", "AI 个人分析");
        return item;
    }

    private String strOrNull(Object value) {
        if (value == null) return null;
        String str = value.toString().trim();
        return str.isEmpty() ? null : str;
    }

    /**
     * Round28 REQ-28-11: AI 分析文本缓存条目（text + 生成日期）。
     * 命中条件：generatedDate 等于服务器当日日期（按日失效，废除 TTL）。
     */
    private static class CachedAnalysis {
        final String text;
        final String generatedDate;

        CachedAnalysis(String text, String generatedDate) {
            this.text = text;
            this.generatedDate = generatedDate;
        }
    }

    /**
     * 根据用户账号基础信息及关联表数据，生成账号信息自动条目。
     * 条目顺序：真实姓名 → 用户名 → 部门 → 团队 → 角色 → 职位 → MBTI → 手机号 → 邮箱
     * 空值字段跳过；基础查询失败返回空列表；MBTI/职位子查询失败仅跳过对应条目。
     */
    private List<Map<String, Object>> getAccountInfoItems(Long userId) {
        List<Map<String, Object>> result = new ArrayList<>();
        int rank = 1;

        // 账号基础信息联合查询（显式列名选取，排除 password_hash / id_card 等敏感字段）
        Map<String, Object> user;
        try {
            user = jdbcTemplate.queryForMap(
                    "SELECT u.username, u.real_name, u.role, u.phone, u.email, " +
                            "d.name AS department_name, t.name AS team_name " +
                            "FROM users u " +
                            "LEFT JOIN departments d ON u.department_id = d.id AND d.deleted = 0 " +
                            "LEFT JOIN teams t ON u.team_id = t.id AND t.deleted = 0 " +
                            "WHERE u.id = ? AND u.deleted = 0", userId);
        } catch (Exception e) {
            log.warn("账号信息查询失败: userId={}, error={}", userId, e.getMessage());
            return Collections.emptyList();
        }

        // MBTI 最新记录查询（独立 try-catch，失败不影响其他条目）
        String mbtiType = null;
        try {
            Map<String, Object> mbti = jdbcTemplate.queryForMap(
                    "SELECT personality_type FROM mbti_reports " +
                            "WHERE user_id = ? AND deleted = 0 " +
                            "ORDER BY generated_at DESC LIMIT 1", userId);
            Object mbtiObj = mbti.get("personality_type");
            if (mbtiObj != null) {
                String tmp = mbtiObj.toString().trim();
                if (!tmp.isEmpty()) mbtiType = tmp;
            }
        } catch (Exception ignored) {}

        // 职位查询（独立 try-catch，失败不影响其他条目）
        String position = null;
        try {
            Map<String, Object> emp = jdbcTemplate.queryForMap(
                    "SELECT position FROM employee_records " +
                            "WHERE registered_user_id = ? AND deleted = 0 " +
                            "AND position IS NOT NULL LIMIT 1", userId);
            Object posObj = emp.get("position");
            if (posObj != null) {
                String tmp = posObj.toString().trim();
                if (!tmp.isEmpty()) position = tmp;
            }
        } catch (Exception ignored) {}

        // 按固定顺序逐字段构造条目（空值跳过）
        rank = addAccountItem(result, rank, user.get("real_name"), "账号信息-真实姓名");
        rank = addAccountItem(result, rank, user.get("username"), "账号信息-用户名");
        rank = addAccountItem(result, rank, user.get("department_name"), "账号信息-部门");
        rank = addAccountItem(result, rank, user.get("team_name"), "账号信息-团队");

        // 角色字段：英文转中文后作为 content
        Object roleObj = user.get("role");
        if (roleObj != null) {
            String roleCn = toChineseRole(roleObj.toString());
            rank = addAccountItem(result, rank, roleCn, "账号信息-角色");
        }

        rank = addAccountItem(result, rank, position, "账号信息-职位");
        rank = addAccountItem(result, rank, mbtiType, "账号信息-MBTI");
        rank = addAccountItem(result, rank, user.get("phone"), "账号信息-手机号");
        rank = addAccountItem(result, rank, user.get("email"), "账号信息-邮箱");

        return result;
    }

    /**
     * 角色英文转中文。null 返回 null；已知角色返回中文名；未知角色原样返回（兜底）。
     */
    private static String toChineseRole(String role) {
        if (role == null) return null;
        return ROLE_CN_MAP.getOrDefault(role, role);
    }

    /**
     * 构造单条账号信息条目并追加到结果列表。值为 null 或空白时跳过，返回原 rank；否则追加条目并返回 rank+1。
     */
    private int addAccountItem(List<Map<String, Object>> result, int rank, Object value, String note) {
        if (value == null) return rank;
        String str = value.toString().trim();
        if (str.isEmpty()) return rank;
        Map<String, Object> item = new HashMap<>();
        item.put("rank_order", rank);
        item.put("content", str);
        item.put("is_auto_filled", true);
        item.put("work_type", "ACCOUNT_INFO");
        item.put("source_note", note);
        result.add(item);
        return rank + 1;
    }
}